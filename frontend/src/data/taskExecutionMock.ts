/**
 * Standard Sales Prospect Research DAG topology (parallel enrichment & web research
 * downstream of Company Discovery, converging into Analysis -> Verification).
 */
function buildStandardEdges(activeIds: readonly string[]): ExecutionEdgeItem[] {
  const isActive = (source: string, target: string) =>
    activeIds.includes(source) && activeIds.includes(target);

  return [
    {
      id: "e-sup-disc",
      source: "supervisor",
      target: "discovery",
      active: isActive("supervisor", "discovery"),
    },
    {
      id: "e-disc-enr",
      source: "discovery",
      target: "enrichment",
      active: isActive("discovery", "enrichment"),
    },
    {
      id: "e-disc-res",
      source: "discovery",
      target: "research",
      active: isActive("discovery", "research"),
    },
    {
      id: "e-enr-ana",
      source: "enrichment",
      target: "analysis",
      active: isActive("enrichment", "analysis"),
    },
    {
      id: "e-res-ana",
      source: "research",
      target: "analysis",
      active: isActive("research", "analysis"),
    },
    {
      id: "e-ana-ver",
      source: "analysis",
      target: "verification",
      active: isActive("analysis", "verification"),
    },
  ];
}

